// Scans src/data/**/*.json (nested dirs become URL namespaces, e.g.
// src/data/bazardor/products.json -> dataset "bazardor/products") and generates:
//   src/generated/datasets.ts  - minified JSON bodies + content-hash ETags for the Worker
//   public/data/<name>.json    - full list, served as a free static asset
//   public/data/<name>/<id>.json - single items, served as free static assets
//   public/_headers            - cache + CORS headers for the static assets
// Runs automatically before `wrangler dev` / `wrangler deploy` (see wrangler.jsonc "build").
import { readdirSync, readFileSync, mkdirSync, writeFileSync, rmSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { dirname, join } from 'node:path'

const DATA_DIR = 'src/data'
const OUT_FILE = 'src/generated/datasets.ts'
const PUBLIC_DIR = 'public/data'
const SAFE = /^[A-Za-z0-9_-]+$/

function collect(dir, base) {
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${entry.name}` : entry.name
    if (entry.isDirectory()) out.push(...collect(join(dir, entry.name), rel))
    else if (entry.name.endsWith('.json')) out.push(rel)
  }
  return out.sort()
}

const files = collect(DATA_DIR, '')

rmSync(PUBLIC_DIR, { recursive: true, force: true })
mkdirSync(PUBLIC_DIR, { recursive: true })

const entries = files.map((rel) => {
  const name = rel.slice(0, -'.json'.length)
  for (const seg of name.split('/')) {
    if (!SAFE.test(seg)) throw new Error(`${rel}: each path segment must use letters, numbers, "-" or "_" only`)
  }

  const items = JSON.parse(readFileSync(join(DATA_DIR, rel), 'utf8'))
  if (!Array.isArray(items)) throw new Error(`${rel}: top level must be an array`)
  const seen = new Set()
  for (const item of items) {
    const id = String(item?.id)
    if (item?.id === undefined || !SAFE.test(id)) throw new Error(`${rel}: every item needs an id using letters, numbers, "-" or "_"`)
    if (seen.has(id)) throw new Error(`${rel}: duplicate id ${id}`)
    seen.add(id)
  }

  const body = JSON.stringify(items)
  const etag = createHash('sha1').update(body).digest('hex').slice(0, 16)

  const listFile = join(PUBLIC_DIR, `${name}.json`)
  mkdirSync(dirname(listFile), { recursive: true })
  writeFileSync(listFile, body)
  const itemDir = join(PUBLIC_DIR, name)
  mkdirSync(itemDir, { recursive: true })
  for (const item of items) writeFileSync(join(itemDir, `${item.id}.json`), JSON.stringify(item))

  return { name, body, etag, count: items.length }
})

const lines = [
  '// Generated by scripts/gen-data.mjs. Do not edit.',
  'export const datasets: Record<string, { body: string; etag: string }> = {',
  ...entries.map((e) => `  ${JSON.stringify(e.name)}: { body: ${JSON.stringify(e.body)}, etag: ${JSON.stringify(e.etag)} },`),
  '}',
  '',
]
mkdirSync('src/generated', { recursive: true })
writeFileSync(OUT_FILE, lines.join('\n'))

writeFileSync(
  'public/_headers',
  ['/data/*', '  Cache-Control: public, max-age=3600', '  Access-Control-Allow-Origin: *', ''].join('\n'),
)

console.log(`gen-data: ${entries.map((e) => `${e.name} (${e.count})`).join(', ')}`)
